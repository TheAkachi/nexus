-- Fase 3: contas, papéis, sessões, links de uso único, auditoria só de inserção, fila de aprovação, mídia,
-- solicitações e aparições na busca (contrato, seção 12).

-- Conta: nome e tipo (o consumidor fica previsto para a Fase 8). Papéis da equipe em português.
ALTER TABLE users ADD COLUMN name text NOT NULL DEFAULT '';
ALTER TABLE users ADD COLUMN kind text NOT NULL DEFAULT 'associado' CHECK (kind IN ('associado','equipe','consumidor'));
ALTER TABLE users DROP CONSTRAINT users_staff_role_check;
UPDATE users SET staff_role='operador' WHERE staff_role='operator';
ALTER TABLE users ADD CONSTRAINT users_staff_role_check CHECK (staff_role IN ('admin','editor','operador'));
UPDATE users SET kind='equipe' WHERE staff_role IS NOT NULL;

-- Papéis do associado por empresa.
ALTER TABLE memberships DROP CONSTRAINT memberships_role_check;
UPDATE memberships SET role = CASE role WHEN 'owner' THEN 'dono' WHEN 'viewer' THEN 'leitura' ELSE role END;
ALTER TABLE memberships ADD CONSTRAINT memberships_role_check CHECK (role IN ('dono','editor','financeiro','leitura'));
ALTER TABLE memberships ADD COLUMN created_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE memberships ADD COLUMN invited_by text REFERENCES users(id) ON DELETE SET NULL;

-- Sessão: id público (para listar e encerrar), criação, último uso (expira por inatividade) e navegador resumido.
ALTER TABLE sessions ADD COLUMN id text;
UPDATE sessions SET id=md5(token_hash);
ALTER TABLE sessions ALTER COLUMN id SET NOT NULL;
CREATE UNIQUE INDEX sessions_id ON sessions(id);
ALTER TABLE sessions ADD COLUMN created_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE sessions ADD COLUMN last_seen_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE sessions ADD COLUMN user_agent text NOT NULL DEFAULT '';
CREATE INDEX sessions_user ON sessions(user_id);

-- Links de uso único: convite (com empresa e papel) e recuperação de senha.
CREATE TABLE access_tokens (
 token_hash text PRIMARY KEY,
 kind text NOT NULL CHECK (kind IN ('convite','recuperacao')),
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 business_id text REFERENCES businesses(id) ON DELETE CASCADE,
 role text CHECK (role IN ('dono','editor','financeiro','leitura')),
 created_by text REFERENCES users(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz NOT NULL,
 used_at timestamptz,
 CHECK (kind='recuperacao' OR (business_id IS NOT NULL AND role IS NOT NULL))
);
CREATE INDEX access_tokens_user ON access_tokens(user_id);

-- Auditoria: valor antes e depois e o IP real. A tabela só aceita INSERT.
ALTER TABLE audit_log ADD COLUMN before jsonb;
ALTER TABLE audit_log ADD COLUMN after jsonb;
ALTER TABLE audit_log ADD COLUMN ip text NOT NULL DEFAULT '';
CREATE INDEX audit_business_date ON audit_log(business_id, created_at);
CREATE FUNCTION audit_log_so_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'audit_log só aceita INSERT'; END $$;
CREATE TRIGGER audit_log_sem_update_delete BEFORE UPDATE OR DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION audit_log_so_insert();
CREATE TRIGGER audit_log_sem_truncate BEFORE TRUNCATE ON audit_log FOR EACH STATEMENT EXECUTE FUNCTION audit_log_so_insert();

-- Empresa gerida pelo painel ou pelo admin: o db:seed deixa de sobrescrever.
ALTER TABLE businesses ADD COLUMN managed_at timestamptz;

-- Fotos e outras mídias: arquivos no volume de mídia (MEDIA_DIR), registro aqui.
CREATE TABLE media (
 id text PRIMARY KEY,
 business_id text REFERENCES businesses(id) ON DELETE CASCADE,
 kind text NOT NULL DEFAULT 'foto' CHECK (kind IN ('foto','midia')),
 mime text NOT NULL,
 width integer NOT NULL,
 height integer NOT NULL,
 bytes integer NOT NULL,
 sha256 text NOT NULL,
 sizes jsonb NOT NULL DEFAULT '[]',
 alt text NOT NULL DEFAULT '',
 status text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente','aprovada','recusada','removida')),
 position integer NOT NULL DEFAULT 0,
 created_by text REFERENCES users(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX media_business ON media(business_id, status);

-- Fila de aprovação (a equipe decide na Fase 4).
CREATE TABLE approvals (
 id text PRIMARY KEY,
 business_id text NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
 kind text NOT NULL CHECK (kind IN ('descricao','foto','catalogo','oferta','banner','avaliacao')),
 resource_id text NOT NULL,
 payload jsonb NOT NULL DEFAULT '{}',
 status text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente','aprovado','recusado','substituido')),
 comment text NOT NULL DEFAULT '',
 submitted_by text REFERENCES users(id) ON DELETE SET NULL,
 submitted_at timestamptz NOT NULL DEFAULT now(),
 decided_by text REFERENCES users(id) ON DELETE SET NULL,
 decided_at timestamptz,
 version integer NOT NULL DEFAULT 1,
 seq bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX approvals_status ON approvals(status, submitted_at);
CREATE INDEX approvals_business ON approvals(business_id, status);

-- Catálogo: versão aprovada (pausar e reativar sem nova análise se nada mudou), recusa e autoria.
ALTER TABLE catalog_items ADD COLUMN approved_version integer;
ALTER TABLE catalog_items ADD COLUMN rejection jsonb;
ALTER TABLE catalog_items ADD COLUMN created_by text REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE catalog_items ADD COLUMN created_at timestamptz NOT NULL DEFAULT now();

-- Solicitações e suporte.
CREATE TABLE requests (
 id text PRIMARY KEY,
 business_id text NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
 kind text NOT NULL CHECK (kind IN ('suporte','criacao','alteracao')),
 subject text NOT NULL,
 status text NOT NULL DEFAULT 'aberta' CHECK (status IN ('aberta','em-andamento','respondida','fechada')),
 briefing jsonb,
 created_by text REFERENCES users(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX requests_business ON requests(business_id, updated_at);
CREATE TABLE request_messages (
 id text PRIMARY KEY,
 request_id text NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
 author_id text REFERENCES users(id) ON DELETE SET NULL,
 side text NOT NULL CHECK (side IN ('associado','equipe')),
 body text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 seq bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX request_messages_request ON request_messages(request_id, created_at);

-- Aparições na busca, contadas no servidor por dia (fuso de São Paulo), sem dado pessoal.
CREATE TABLE business_daily (
 day date NOT NULL,
 business_id text NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
 search_impressions integer NOT NULL DEFAULT 0 CHECK (search_impressions >= 0),
 PRIMARY KEY (day, business_id)
);
